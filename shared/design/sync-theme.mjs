import { readFile, writeFile } from "node:fs/promises";
const base = new URL("./", import.meta.url);
const tokens = JSON.parse(await readFile(new URL("companion-tokens.json", base), "utf8"));
const kebab = (key) => key.replace(/[A-Z]/g, (letter) => "-" + letter.toLowerCase());
const css = `/* Generated by shared/design/sync-theme.mjs. Edit companion-tokens.json. */\n:root {\n${Object.entries(tokens.colors).map(([key,value]) => `  --companion-${kebab(key)}: ${value};`).join("\n")}\n  --companion-surface-opacity: ${tokens.surfaceOpacity};\n${Object.entries(tokens.radius).map(([key,value]) => `  --companion-radius-${key}: ${value}px;`).join("\n")}\n}\n`;
const kotlin = `// Generated by shared/design/sync-theme.mjs. Edit companion-tokens.json.\npackage com.waymate.app.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\ninternal object CompanionPalette {\n${Object.entries(tokens.colors).map(([key,value]) => `    val ${key[0].toUpperCase()+key.slice(1)} = Color(0xFF${value.slice(1)})`).join("\n")}\n    const val SurfaceOpacity = ${tokens.surfaceOpacity}f\n}\n`;
for (const [path, content] of [
  [new URL("companion-theme.css", base), css],
  [new URL("../../vehicle-app/app/src/main/java/com/waymate/app/ui/theme/CompanionPalette.kt", base), kotlin],
]) {
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Theme out of sync: ${path.pathname}`);
  } else await writeFile(path, content);
}
console.log(process.argv.includes("--check") ? "Web and Pleos theme tokens match." : "Web and Pleos theme tokens generated.");
